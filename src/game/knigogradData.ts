const STORAGE_KEY = 'knigograd_bgiik_full_v1';

export function createEmptyTaskProgress(): TaskProgress {
  return { completed: false, bibliks: 0, mistakes: 0, usedHint: false };
}

export function createInitialSave(): KnigogradSave {
  return {
    w1: [0, 1, 2, 3].map(createEmptyTaskProgress),
    w2: [0, 1, 2, 3].map(createEmptyTaskProgress),
    w3: [0, 1, 2, 3].map(createEmptyTaskProgress),
    exhibitionSections: { life: [], research: [], expedition: [] },
    magazineHeadline: 'От эскиза до плаката: как рождается авторская афиша',
    festivalName: 'Библионочь: квиз, книги и мастер-классы',
    soundMuted: false,
    subscribers: 250,
    coins: 500,
    unlockedUpgrades: [],
    hiredStaff: {},
    releases: [],
    publishedTrends: 0,
  };
}

export function loadKnigogradSave(): KnigogradSave {
  if (typeof window === 'undefined') return createInitialSave();
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) return createInitialSave();
    const parsed = JSON.parse(raw) as Partial<KnigogradSave>;
    const init = createInitialSave();
    return {
      ...init,
      ...parsed,
      w1: Array.isArray(parsed.w1) && parsed.w1.length === 4 ? parsed.w1 : init.w1,
      w2: Array.isArray(parsed.w2) && parsed.w2.length === 4 ? parsed.w2 : init.w2,
      w3: Array.isArray(parsed.w3) && parsed.w3.length === 4 ? parsed.w3 : init.w3,
      exhibitionSections: parsed.exhibitionSections?.life
        ? parsed.exhibitionSections
        : init.exhibitionSections,
      subscribers: typeof parsed.subscribers === 'number' ? parsed.subscribers : init.subscribers,
      coins: typeof parsed.coins === 'number' ? parsed.coins : init.coins,
      unlockedUpgrades: Array.isArray(parsed.unlockedUpgrades) ? parsed.unlockedUpgrades : [],
      hiredStaff: parsed.hiredStaff && typeof parsed.hiredStaff === 'object' ? parsed.hiredStaff : {},
      releases: Array.isArray(parsed.releases) ? parsed.releases : [],
      publishedTrends: typeof parsed.publishedTrends === 'number' ? parsed.publishedTrends : 0,
    };
  } catch {
    return createInitialSave();
  }
}

export function saveKnigogradSave(data: KnigogradSave): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch {
    // Ignore storage quota issues
  }
}

